import { HoverEntry } from './types';

export const FIELD_PREFIX_HOVERS: HoverEntry[] = [
  {
    label: 'v',
    detail: 'Значение поля',
    documentation: 'Значение поля. Вне группы `(...)` — конкатенация значений всех повторений; ' +
      'внутри группы — только значение текущего повторения.'
  },
  {
    label: 'd',
    detail: 'Проверка присутствия поля/подполя',
    documentation: 'Проверка присутствия поля/подполя. **Сам по себе никогда не выводит ' +
      'текст** — значение через `d` получить нельзя, для этого нужен `v`. Используется в ' +
      '`p()`/`a()` или как «якорь» для условного/повторяющегося литерала — `"текст"d200` ' +
      'печатает текст, если d200 присутствует, но само значение поля не выводит.'
  },
  {
    label: 'n',
    detail: 'Проверка отсутствия поля/подполя',
    documentation: 'Проверка **отсутствия** поля/подполя (обратное `d`). С подполем — истина, ' +
      'если поле есть, а подполя нет; без подполя — истина, если поля нет вовсе. Как и `d`, ' +
      'текста не выводит.'
  },
  {
    label: 'g',
    detail: 'Глобальная переменная формата',
    documentation: 'Глобальная переменная формата (устанавливается через `&uf(\'+7...\')`/' +
      '`&uf(\'+1...\')`). Те же правила, что у `v`: вне группы — конкатенация всех повторений, ' +
      'внутри группы — только текущее.'
  }
];

export function findFieldPrefixHover(prefix: string): HoverEntry | undefined {
  return FIELD_PREFIX_HOVERS.find(entry => entry.label === prefix.toLowerCase());
}
