export function getUniforFunctionsByCategory(category?: string): UniforFunction[] {
  if (category) {
    return UNIFOR_FUNCTIONS.filter(func => func.category === category);
  }
  return UNIFOR_FUNCTIONS;
}

export function getUniforCategories(): string[] {
  const categories = new Set(UNIFOR_FUNCTIONS.map(func => func.category));
  return Array.from(categories);
}
