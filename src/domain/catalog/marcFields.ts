export function findField(fieldNumber: string): FieldInfo | undefined {
  return FIELD_DEFINITIONS.find(field => field.number === fieldNumber);
}

export function findSubfield(fieldNumber: string, subfieldCode: string): string | undefined {
  return findField(fieldNumber)?.subfields?.[subfieldCode];
}